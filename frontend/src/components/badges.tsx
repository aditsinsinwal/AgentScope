import type {ReportSource} from "../api/types";

/** Replay reports re-score recorded outputs; they are not model runs, so say so loudly. */
export function SourceBadge({source}: {source: ReportSource}) {
  return source === "replay"
    ? <span className="badge badge--replay" title="Recorded outputs re-scored; no model was called">REPLAY</span>
    : <span className="badge badge--generated" title="Outputs generated by a model during this run">generated</span>;
}

export function StatusBadge({status}: {status: string}) {
  const tone = status === "completed" ? "ok" : /fail|timed_out|cancel/.test(status) ? "bad" : "info";
  return <span className={`badge badge--${tone}`}>{status.replaceAll("_", " ")}</span>;
}

export function PassBadge({passed}: {passed: boolean}) {
  return <span className={`badge ${passed ? "badge--ok" : "badge--bad"}`}>{passed ? "pass" : "fail"}</span>;
}
